/* =========================================================
   LOAD EVENT FUNCTION
========================================================= */

function loadEvent(data) {


    /* =====================================================
       PAGE TITLE
    ===================================================== */

    document.title =
        `${data.title} | QAICYS 2026`;


    /* =====================================================
       HERO
    ===================================================== */

    getElement(
        "eventTitle"
    ).textContent =
        data.title;


    getElement(
        "eventSubtitle"
    ).textContent =
        `QAICYS 2026 • ${data.category}`;


    /* =====================================================
       EVENT DETAILS
    ===================================================== */

    getElement(
        "teamSize"
    ).textContent =
        data.teamSize ||
        "To Be Announced";


    getElement(
        "eventDate"
    ).textContent =
        data.date ||
        "To Be Announced";


    getElement(
        "eventVenue"
    ).textContent =
        data.venue ||
        "To Be Announced";


    getElement(
        "eventTime"
    ).textContent =
        data.time ||
        "To Be Announced";


    /* =====================================================
       RULES
    ===================================================== */

    const rulesContainer =
        getElement(
            "rulesContainer"
        );


    rulesContainer.innerHTML = "";


    data.rules.forEach(
        function(rule, index) {


            const ruleItem =
                document.createElement(
                    "div"
                );


            ruleItem.className =
                "rule-item";


            ruleItem.innerHTML = `

                <span class="rule-number">
                    ${String(
                        index + 1
                    ).padStart(
                        2,
                        "0"
                    )}
                </span>

                <p class="rule-text">
                    ${escapeHTML(rule)}
                </p>

            `;


            rulesContainer.appendChild(
                ruleItem
            );

        }
    );


    /* =====================================================
       FACULTY COORDINATOR
    ===================================================== */

    const facultyName =
        getElement(
            "facultyName"
        );


    const facultyPhone =
        getElement(
            "facultyPhone"
        );


    facultyName.textContent =
        data.facultyCoordinator.name;


    facultyPhone.textContent =
        data.facultyCoordinator.phone;


    facultyPhone.href =
        createWhatsAppLink(
            data.facultyCoordinator.phone,
            data.facultyCoordinator.name,
            data.title
        );


    facultyPhone.target =
        "_blank";


    facultyPhone.rel =
        "noopener noreferrer";


    /* =====================================================
       STUDENT COORDINATORS
    ===================================================== */

    const studentContainer =
        getElement(
            "studentCoordinatorList"
        );


    studentContainer.innerHTML = `

        <span class="coordinator-label">
            STUDENT COORDINATOR
        </span>

    `;


    data.studentCoordinators.forEach(
        function(student) {


            const person =
                document.createElement(
                    "div"
                );


            person.className =
                "student-person";


            const whatsappLink =
                createWhatsAppLink(
                    student.phone,
                    student.name,
                    data.title
                );


            person.innerHTML = `

                <h3>
                    ${escapeHTML(student.name)}
                </h3>

                <a
                    class="phone-number"
                    href="${whatsappLink}"
                    target="_blank"
                    rel="noopener noreferrer"
                >
                    ${escapeHTML(student.phone)}
                </a>

            `;


            studentContainer.appendChild(
                person
            );

        }
    );


    /* =====================================================
       EXPLORE ALL EVENTS
    ===================================================== */

    const exploreButton =
        getElement(
            "exploreEvents"
        );


    if (exploreButton) {

        exploreButton.href =
            data.eventPage;

    }

    const backButton =
        getElement("backToEvents");

    if (backButton) {

        backButton.href =
            data.eventPage;

    }


    /* =====================================================
       REGISTER NOW
    ===================================================== */

    const registerButton =
        getElement(
            "registerNow"
        );


    if (registerButton) {

        if (data.registrationClosed) {
            registerButton.textContent = "REGISTRATION CLOSED";
            registerButton.href = "#";
            registerButton.setAttribute("aria-disabled", "true");
            registerButton.classList.add("registration-closed");
            registerButton.addEventListener("click", function (event) {
                event.preventDefault();
                if (data.title == "SYNAPSE"){
                    window.alert(
                        "Registrations for Synapse are closed. Kindly register on other events."
                    );
                }

                else if (data.title == "HENNA HUES"){
                    window.alert(
                        "Registrations for Henna Hues are closed. Kindly register on other events."
                    );
                }

                else if (data.title == "PITCH PERFECT"){
                    window.alert(
                        "Registrations for Pitch Perfect are closed. Kindly register on other events."
                    );
                }

                else if (data.title == "BID BYTE"){
                    window.alert(
                        "Registrations for Bid Byte are closed. Kindly register on other events."
                    );
                }

                else if (data.title == "PROMPTOPIA"){
                    window.alert(
                        "Registrations for Promptopia are closed. Kindly register on other events."
                    );
                }

                else if (data.title == "PIXEL CIPHER"){
                    window.alert(
                        "Registrations for Pixel Cipher are closed. Kindly register on other events."
                    );
                }

            });
        } else {
            registerButton.href =
                `register.html?event=${encodeURIComponent(eventId)}`;
        }

    }

}


/* =========================================================
   WHATSAPP LINK
========================================================= */

function createWhatsAppLink(
    phone,
    coordinatorName,
    eventName
) {


    const number =
        phone.replace(
            /\D/g,
            ""
        );


    const message =
`Hello ${coordinatorName},

I would like to know more about the ${eventName} event in QAICYS 2026.

Could you please provide me with more information regarding the event?

Thank you.`;


    return (
        "https://wa.me/" +
        number +
        "?text=" +
        encodeURIComponent(
            message
        )
    );

}


/* =========================================================
   HTML ESCAPE
========================================================= */

function escapeHTML(value) {

    return String(value)

        .replace(
            /&/g,
            "&amp;"
        )

        .replace(
            /</g,
            "&lt;"
        )

        .replace(
            />/g,
            "&gt;"
        )

        .replace(
            /"/g,
            "&quot;"
        )

        .replace(
            /'/g,
            "&#039;"
        );

}


